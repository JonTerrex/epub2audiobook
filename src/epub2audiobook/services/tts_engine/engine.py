from pathlib import Path
from typing import Dict, List, Optional
import soundfile as sf
import numpy as np
from kokoro import KPipeline

from shared.schemas import TextChunk


class TTSEngine:
    """TTS engine powered by Kokoro-TTS.

    Receives TextChunk objects and generates their corresponding .wav audio files.
    """

    def __init__(
        self,
        lang_code: str = "e",  # 'e' = Spanish ('a' = American English, 'b' = British English)
        default_voice: str = "ef_dora",  # Female voice in Spanish by default
        sample_rate: int = 24000,
    ):
        self.lang_code = lang_code
        self.default_voice = default_voice
        self.sample_rate = sample_rate

        # Initialize the Kokoro pipeline (automatically downloads the model if it doesn't exist)
        self.pipeline = KPipeline(lang_code=self.lang_code)

    def synthesize_chunk(
        self,
        chunk: TextChunk,
        output_dir: str | Path,
        voice: Optional[str] = None,
    ) -> Path:
        """Sintetiza un único TextChunk y guarda el archivo .wav en disk.

        Args:
            chunk: Objeto TextChunk with normalized text and metadata.
            output_dir: File directory where the resulting audio will be saved.
            voice: Optional name of the voice to use (overrides the default voice).

        Returns:
            Path to the generated .wav file.
        """
        output_path = Path(output_dir)
        output_path.mkdir(parents=True, exist_ok=True)
        # Select the voice to use: either the provided one or the default
        selected_voice = voice or self.default_voice
        # Generate the output file path
        file_name = f"{chunk.chunk_id}.wav"
        destination_file = output_path / file_name
        # Avoid re-generating the audio if it already exists
        if destination_file.exists():
            return destination_file

        # Kokoro proccesses the text in chunks, so we can use the generator to get audio segments
        generator = self.pipeline(
            chunk.text,
            voice=selected_voice,
            speed=1.0,
            split_pattern=r"\n+",
        )
        # Collect all audio segments generated by the pipeline
        audio_segments = []
        for _, _, audio in generator:
            audio_segments.append(audio)
        # Check if any audio was generated
        if not audio_segments:
            raise ValueError(f"No audio was generated for chunk {chunk.chunk_id}")
        
        # Concatenate audio segments if the chunk generated more than one
        full_audio = (
            np.concatenate(audio_segments) 
            if len(audio_segments) > 1 
            else audio_segments[0])

        # Save  the audio to the destination file using soundfile
        sf.write(destination_file, full_audio, self.sample_rate)

        return destination_file
    def synthesize_chunks(
        self,
        chunks: List[TextChunk],
        output_dir: str | Path,
        voice_mapping: Optional[Dict[str, str]] = None,
    ) -> List[Path]:
        """Proccess a list of TextChunks and save the resulting .wav files to disk.

        Args:
            chunks: List of TextChunk objects with normalized text and metadata.
            output_dir: Directory where the resulting audio files will be saved.
            voice_mapping: Optional mapping of chunk_id to voice name.

        Returns:
            List of paths to the generated .wav files.
        """
        # Initialize the output paths list and the voice mapping
        generated_files : List[Path]=[]  
        mapping = voice_mapping if voice_mapping else {}

        # Process each chunk and synthesize its audio
        for chunk in chunks:
            voice = voice_mapping.get(chunk.chunk_id, self.default_voice)
            wav_path = self.synthesize_chunk(
                chunk,
                 output_dir, 
                 voice)
            generated_files.append(wav_path)
        return generated_files 